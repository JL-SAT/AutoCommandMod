export function getKeyName(keyCode: number): string {
  return LWJGL_MAP[keyCode] || `KEY_${keyCode}`;
}

export function getLwjglCodeFromEvent(e: KeyboardEvent): number {
  if (BROWSER_CODE_TO_LWJGL[e.code]) {
    return BROWSER_CODE_TO_LWJGL[e.code];
  }
  // Fallback for simple letters
  const upper = e.key.toUpperCase();
  for (const [codeStr, name] of Object.entries(LWJGL_MAP)) {
    if (name === upper) return parseInt(codeStr, 10);
  }
  return 0;
}
